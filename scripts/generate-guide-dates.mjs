#!/usr/bin/env node
/**
 * Generates lib/guides/guide-dates.generated.ts: a slug -> { datePublished,
 * dateModified } map built from this repo's actual git history for each
 * app/guides/<slug>/page.tsx file (first commit that added it, most recent
 * commit that touched it).
 *
 * Run from the repo root whenever a guide is added or edited and the
 * Article schema's dates should reflect it:
 *   node scripts/generate-guide-dates.mjs
 *
 * Baked into a committed file rather than read live at build time because
 * the production build environment is not guaranteed to have full git
 * history (a shallow clone would silently produce wrong or missing dates).
 */
import { execSync } from 'node:child_process'
import { readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const GUIDES_DIR = join(ROOT, 'app', 'guides')
const OUTPUT_FILE = join(ROOT, 'lib', 'guides', 'guide-dates.generated.ts')

const RECORD_SEP = '\x01'

function toDateOnly(isoWithOffset) {
  return isoWithOffset.slice(0, 10)
}

function knownGuideSlugs() {
  return readdirSync(GUIDES_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('['))
    .map((entry) => entry.name)
    .filter((slug) => {
      try {
        return statSync(join(GUIDES_DIR, slug, 'page.tsx')).isFile()
      } catch {
        return false
      }
    })
}

function buildDateMap() {
  const output = execSync(
    `git log --format=${RECORD_SEP}%cI --name-only --diff-filter=ACMR -- app/guides`,
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 1024 * 1024 * 64 },
  )

  // git log is newest-first, so the first time we see a file is its most
  // recent touch (dateModified) and the last time we see it is its original
  // add (datePublished).
  const lastSeen = new Map()
  const firstSeen = new Map()

  let currentDate = null
  for (const line of output.split('\n')) {
    if (line.startsWith(RECORD_SEP)) {
      currentDate = toDateOnly(line.slice(1))
      continue
    }
    const match = line.match(/^app\/guides\/([^/]+)\/page\.tsx$/)
    if (!match || !currentDate) continue
    const slug = match[1]
    if (!lastSeen.has(slug)) lastSeen.set(slug, currentDate)
    firstSeen.set(slug, currentDate)
  }

  const map = {}
  for (const slug of knownGuideSlugs()) {
    const dateModified = lastSeen.get(slug)
    const datePublished = firstSeen.get(slug)
    if (dateModified && datePublished) {
      map[slug] = { datePublished, dateModified }
    }
  }
  return map
}

function renderFile(map) {
  const entries = Object.keys(map)
    .sort()
    .map((slug) => `  '${slug}': { datePublished: '${map[slug].datePublished}', dateModified: '${map[slug].dateModified}' },`)
    .join('\n')

  return `/**
 * Generated by scripts/generate-guide-dates.mjs from git history. Do not
 * edit by hand; re-run the script after guide content changes and commit
 * the result.
 */
export type GuideDates = { datePublished: string; dateModified: string }

export const GUIDE_DATES: Record<string, GuideDates> = {
${entries}
}
`
}

const map = buildDateMap()
writeFileSync(OUTPUT_FILE, renderFile(map))
console.log(`Wrote ${Object.keys(map).length} guide date entries to ${OUTPUT_FILE}`)
